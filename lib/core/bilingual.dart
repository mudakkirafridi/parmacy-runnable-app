String englishLabel(String label) {
  final clean = label.split(RegExp(r'\s+/\s+(?=[\u0600-\u06ff])')).first.trim();
  final english = labelAliases[clean] ?? clean;
  for (final entry in urduLabels.entries) {
    if (entry.value == english) return entry.key;
  }
  return english;
}

String localizedLabel(String label, {bool urdu = false}) {
  final english = englishLabel(label);
  return urdu ? urduLabels[english] ?? english : english;
}

// Kept for callers supplying canonical English labels, never combines languages.
String bilingual(String label) => localizedLabel(label);

